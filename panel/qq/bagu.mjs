/**
 * 鱼八股特征表：她回复里模板化腔调的可检测模式，三个地方共用这一份——
 *   1) brain.reply()  出口：正文命中 ≥2 类就重roll一次（brain.mjs）
 *   2) brain.history() 历史：她自己过去的八股回复降权成大意，不再当逐字范文（brain.mjs）
 *   3) fugao-stats.mjs 账本：线上消息按类统计，看哪类高发（ops/fugao-stats.mjs）
 *
 * 清单来自对大肥鱼/乙女腔的观察（2026-11-25），按误报风险甄别过：
 *   收了的：签收腔、接话腔、比重量、定调收尾、降维断言、三连排比、标点堆叠、开放式邀请收尾
 *   没收的（正则不可靠，走角色卡写作指导）：省略主宾「凹短」、单字实词（交/接/立）——
 *   这两类在角色卡「四、说话方式」用因果链管，别往这里塞。
 *
 * 判定口径：baguScore = 命中的「类」数。单类命中可能是正常话（比如「不是…而是…」汉语本来就常用），
 * ≥2 类才判八股——一处判定一处保守，别把正常聊天误杀成重roll。
 */

export const BAGU = [
  // 签收腔：把收到的话当包裹签收（角色卡黑名单原有「收下了/记着了/存好」的近亲）
  { cat: '签收腔', re: /这个账我记(住|下)了?|这话我(记下了|收下|留着)|几条全中|这句我(记|收)下了?/ },
  // 接话腔：把「回应别人」说成接球动作
  { cat: '接话腔', re: /(这|那)句(话)?接(住|得漂亮|的漂亮)|没接你(那)?[句条话]|这个我认[。，！？]|认得实|认下来/ },
  // 比重量：给自己的语气称重（「比刚才稳」这类自我旁白，语C 腔的残留）
  { cat: '比重量', re: /声音没抖|比(之前|刚才|上次)[^。！？]{0,8}(都)?(重|轻|强|稳|平)[。！？]|^很(平|直|稳)[，。！？]/ },
  // 定调收尾：冷冰冰替人拿主意 / 单字定调
  { cat: '定调收尾', re: /^行[。！？!?~\s]*$|你(自己)?掂量|我不(拦|催)|问别人还是问自己|还是你自己想明白的|你看这样行吗\s*[？?]?$/ },
  // 降维断言：公式化总结腔
  { cat: '降维断言', re: /说白了|本质上|说到底|先说(一句)?结论|想象一下|手术刀般?|什么心思都写在|不是[^。！？]{1,24}，?而是[^。！？]/ },
  // 三连排比：「放下、放下、放下」
  { cat: '三连排比', re: /([^，。、！？\s]{1,4})、\1、\1/ },
  // 标点堆叠：一条里两个破折号，或冒号引号破折号齐上
  { cat: '标点堆叠', re: /——[^。！？]{2,}——|：[^。！？]{2,}“[^。！？]{2,}——/ },
  // 开放式邀请收尾：推销式贴心助手（乙女腔的「如果你愿意，我们可以…」）
  { cat: '开放式邀请', re: /如果你(愿意|想|不介意)[^。！？]{0,14}我们(可以|一起|再|也)/ },
];

/** 命中的类别名列表（同一条文本同类多次命中只算一次） */
export function baguHits(text) {
  const t = String(text || '');
  if (!t) return [];
  return BAGU.filter((p) => p.re.test(t)).map((p) => p.cat);
}

/** 命中类别数：≥2 才判八股（各类判定点共用这个阈值口径） */
export function baguScore(text) {
  return baguHits(text).length;
}

/** 历史降权：把她过去的八股回复改写成「大意」，不再是逐字范文。
 *  保留前 50 字足够看出当时聊什么，截断后句式不完整，模仿价值大幅下降；
 *  「（大意是：…）」和历史里「（隔了 N 小时）」同属记录格式，模型不会当话说出去。 */
export function baguRewrite(text) {
  const t = String(text || '').trim();
  return `（有一次说得比较僵，大意是：${t.slice(0, 50)}${t.length > 50 ? '…' : ''}）`;
}
